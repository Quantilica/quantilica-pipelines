-- Índice de difusão: proporção de subitens (código de 7 dígitos, NIVEL = 7)
-- com variação positiva no período, por índice e localidade.
SELECT
	PERIODO,
	INDICE,
	NIVEL_TERRITORIAL_ID,
	NIVEL_TERRITORIAL,
	LOCALIDADE_ID,
	LOCALIDADE,
	COUNT(*) AS TOTAL_SUBITENS,
	AVG(
		CASE
			WHEN VARIACAO > 0 THEN 1.0
			ELSE 0.0
		END
	) AS INDICE_DIFUSAO
FROM
	ANALYTICS.INFLACAO
WHERE
	NIVEL = 7
	AND VARIACAO IS NOT NULL
GROUP BY
	PERIODO,
	INDICE,
	NIVEL_TERRITORIAL_ID,
	NIVEL_TERRITORIAL,
	LOCALIDADE_ID,
	LOCALIDADE;
