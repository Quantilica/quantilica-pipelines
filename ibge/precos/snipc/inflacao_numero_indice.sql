WITH
	BASE AS (
		SELECT
			P.DATA_INICIO AS PERIODO,
			CASE D.TABELA_SIDRA_ID
				WHEN '1736' THEN 'INPC'
				WHEN '1737' THEN 'IPCA'
				WHEN '3065' THEN 'IPCA-15'
			END AS INDICE,
			DIM.D2N AS VARIAVEL,
			CASE
				WHEN D.V ~ '^-?[0-9]' THEN D.V::NUMERIC
			END AS VALOR
		FROM
			DADOS D
			JOIN PERIODO P ON D.PERIODO_ID = P.ID
			JOIN DIMENSAO DIM ON D.DIMENSAO_ID = DIM.ID
		WHERE
			D.TABELA_SIDRA_ID IN ('1736', '1737', '3065')
			AND D.ATIVO = TRUE
	)
SELECT
	PERIODO,
	INDICE,
	MAX(
		CASE
			WHEN VARIAVEL LIKE '%Número-índice%' THEN VALOR
		END
	) AS NUMERO_INDICE,
	MAX(
		CASE
			WHEN VARIAVEL LIKE '%Variação mensal%' THEN VALOR
		END
	) AS VARIACAO_MENSAL,
	MAX(
		CASE
			WHEN VARIAVEL LIKE '%3 meses%' THEN VALOR
		END
	) AS VARIACAO_ACUMULADA_3_MESES,
	MAX(
		CASE
			WHEN VARIAVEL LIKE '%6 meses%' THEN VALOR
		END
	) AS VARIACAO_ACUMULADA_6_MESES,
	MAX(
		CASE
			WHEN VARIAVEL LIKE '%no ano%' THEN VALOR
		END
	) AS VARIACAO_ACUMULADA_NO_ANO,
	MAX(
		CASE
			WHEN VARIAVEL LIKE '%12 meses%' THEN VALOR
		END
	) AS VARIACAO_ACUMULADA_12_MESES
FROM
	BASE
GROUP BY
	PERIODO,
	INDICE;
