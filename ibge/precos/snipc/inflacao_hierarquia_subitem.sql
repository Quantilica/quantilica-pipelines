-- Dimensão hierárquica do SNIPC construída a partir dos prefixos do código:
--   subitem (7) -> item (4) -> subgrupo (2) -> grupo (1).
-- O nome de cada nível é deduplicado pegando o do período mais recente,
-- evitando fan-out quando o IBGE alterou a descrição de um código ao longo do tempo.
WITH
	NIVEIS AS (
		SELECT DISTINCT
			ON (CODIGO_ITEM, NIVEL) CODIGO_ITEM AS CODIGO,
			NOME_ITEM AS NOME,
			NIVEL
		FROM
			ANALYTICS.INFLACAO
		WHERE
			CODIGO_ITEM <> '0'
		ORDER BY
			CODIGO_ITEM,
			NIVEL,
			PERIODO DESC
	),
	SUBITEM AS (
		SELECT CODIGO, NOME FROM NIVEIS WHERE NIVEL = 7
	),
	ITEM AS (
		SELECT CODIGO, NOME FROM NIVEIS WHERE NIVEL = 4
	),
	SUBGRUPO AS (
		SELECT CODIGO, NOME FROM NIVEIS WHERE NIVEL = 2
	),
	GRUPO AS (
		SELECT CODIGO, NOME FROM NIVEIS WHERE NIVEL = 1
	)
SELECT
	S.CODIGO AS CODIGO_SUBITEM,
	S.NOME AS SUBITEM,
	LEFT(S.CODIGO, 4) AS CODIGO_ITEM,
	I.NOME AS ITEM,
	LEFT(S.CODIGO, 2) AS CODIGO_SUBGRUPO,
	SG.NOME AS SUBGRUPO,
	LEFT(S.CODIGO, 1) AS CODIGO_GRUPO,
	G.NOME AS GRUPO
FROM
	SUBITEM S
	LEFT JOIN ITEM I ON LEFT(S.CODIGO, 4) = I.CODIGO
	LEFT JOIN SUBGRUPO SG ON LEFT(S.CODIGO, 2) = SG.CODIGO
	LEFT JOIN GRUPO G ON LEFT(S.CODIGO, 1) = G.CODIGO;
